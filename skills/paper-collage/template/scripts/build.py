"""Build the HyperFrames project from scripts/scenes.py. MIT License.

Writes compositions/<id>.html for every scene, index.html (scene hosts, optional voiceover,
captions and SFX, inlined CSS), and optionally assets/lib/captions.js + compositions/captions.html.
Everything in scenes.py is authored in content seconds; with CONFIG["target_seconds"] set, the
page plays SPEED times faster (nothing is cut) and the voiceover is time-stretched to match.

Run from the project root: python3 scripts/build.py
"""
import json
