import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from scenes import CONFIG, SCENES  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SFX_NAMES = ("typing", "pop", "click-soft", "whoosh-short")
GENERATED = "Generated by scripts/build.py from scripts/scenes.py."
SFX_DIRS = [
    os.environ.get("PAPER_COLLAGE_SFX", ""),
    str(ROOT / ".claude/skills/media-use/audio/assets/sfx"),
    str(Path.home() / ".claude/skills/media-use/audio/assets/sfx"),
    str(Path.home() / ".agents/skills/media-use/audio/assets/sfx"),
]


def timeline():
    """Resolve start, exit, push and push-out for every scene (content seconds)."""
    push = CONFIG.get("push", 0.4)
    ids = [s["id"] for s in SCENES]
    if len(set(ids)) != len(ids):
        sys.exit("scenes.py: scene ids must be unique")
    out, cursor = [], 0.0
    for i, s in enumerate(SCENES):
        start = float(s.get("start", cursor))
        last = i == len(SCENES) - 1
        out.append({**s, "start": start, "push": i > 0,
                    "pushout": None if last else round(s["dur"] - push, 3),
                    "exit": s.get("exit", None if last else round(s["dur"] - 0.9, 3))})
        cursor = start + s["dur"] - push
    end = max(w["start"] + w["dur"] for w in out)
    return out, round(end, 3)


def backdrop(s, real):
    p = s.get("presenter")
    if p:
        media = (f'<video id="{s["id"]}-video" class="clip" src="{p["src"]}" data-start="0" data-duration="{real(s["dur"])}" '
                 f'data-track-index="0" muted playsinline></video>' if p.get("video") else f'<img src="{p["src"]}" alt="" />')
        return f'<div class="cg-presenter" data-frames="{p.get("frames", "0:1")}">{media}</div>'
    if s.get("backdrop") == "plain":
        return ""
    return '<div class="cg-bg-grid"></div><div class="cg-bg-crumple"></div>'


def write_scene(s, speed, real):
    attrs = [f'data-seed="{s.get("seed", 1)}"']
    if s["exit"] is not None:  # the last scene holds to the end by default
        attrs.append(f'data-exit="{s["exit"]}"')
    if s["push"]:
        attrs.append('data-push="1"')
    if s["pushout"] is not None:
        attrs.append(f'data-pushout="{s["pushout"]}"')
    if s.get("presenter"):
        attrs.append('data-zoom="0"')
    sid, world = s["id"], "\n            ".join(s["world"])
    html = f"""<!doctype html>
<html>
  <head>
    <meta charset="UTF-8" />
  </head>
  <body>
    <!-- {GENERATED} Edit scenes.py, not this file. -->
    <template id="{sid}-template">
      <div id="{sid}-root" data-composition-id="{sid}" data-width="1080" data-height="1920" data-duration="{real(s["dur"])}" style="position: absolute; inset: 0">
        <div id="{sid}-stage" class="cg-stage" {" ".join(attrs)} style="--bg: {s.get("bg", "#BEE5D2")}">
          {backdrop(s, real)}
          <div class="cg-world">
            {world}
          </div>
        </div>
      </div>
      <script>
        Collage.scene("{sid}", "{sid}-stage", {s["dur"]}, {speed});
      </script>
    </template>
  </body>
</html>
"""
    (ROOT / "compositions" / f"{sid}.html").write_text(html)
    return html


def prune_compositions(keep):
    """Delete scene files build.py wrote earlier for scenes that are no longer in SCENES."""
    for f in (ROOT / "compositions").glob("*.html"):
        if f.stem not in keep and GENERATED in f.read_text():
            f.unlink()
            print("removed stale", f.relative_to(ROOT))


def caption_rows(words, real):
    """Group words into 1 to 3 word caps chunks that break at punctuation."""
    chunks, cur = [], []
    for w in words:
        cur.append(w)
        if re.search(r"[,.?!]$", w["w"]) or len(cur) == 3 or len(" ".join(x["w"] for x in cur)) >= 14:
            chunks, cur = chunks + [cur], []
    chunks = chunks + [cur] if cur else chunks
    rows = []
    for i, c in enumerate(chunks):
        nxt = chunks[i + 1][0]["s"] if i + 1 < len(chunks) else c[-1]["e"] + 0.5
        text = " ".join(x["w"] for x in c).rstrip(".").upper()
        rows.append([real(c[0]["s"]), real(min(nxt, c[-1]["e"] + 0.45)), text])
    return rows


def write_captions(end_real, real):
    path = CONFIG.get("words")
    if not path:
        return False
    rows = caption_rows(json.loads((ROOT / path).read_text()), real)
    (ROOT / "assets/lib/captions.js").write_text(f"window.CAPTIONS = {json.dumps(rows)};\nwindow.CAPTIONS_END = {end_real};\n")
    (ROOT / "compositions/captions.html").write_text(CAPTIONS_HTML.replace("__END__", str(end_real)))
    return True


def stretch_vo(speed):
    """Voiceover path for the page; time-stretched (pitch kept) when speed != 1."""
    src = CONFIG.get("vo")
    if not src or speed == 1:
        return src
    out = Path(src).with_name(f"{Path(src).stem}-x{speed:.4f}.wav")
    chains = [f"rubberband=tempo={speed:.6f}:pitchq=quality", f"atempo={speed:.6f}"]
    for chain in chains:
        r = subprocess.run(["ffmpeg", "-nostdin", "-loglevel", "error", "-y", "-i", str(ROOT / src), "-af", chain,
                            "-ar", "48000", str(ROOT / out)], capture_output=True, text=True)
        if r.returncode == 0:
            return str(out)
    sys.exit(f"ffmpeg could not time-stretch {src}: {r.stderr.strip()}")


def copy_sfx():
    """Copy the four SFX from the HyperFrames media-use skill (Pixabay licence, not bundled)."""
    dst = ROOT / "assets/sfx"
    if all((dst / f"{n}.mp3").exists() for n in SFX_NAMES):
        return True
    for d in filter(None, SFX_DIRS):
        if all((Path(d) / f"{n}.mp3").exists() for n in SFX_NAMES):
            dst.mkdir(parents=True, exist_ok=True)
            for n in SFX_NAMES:
                shutil.copy(Path(d) / f"{n}.mp3", dst / f"{n}.mp3")
            return True
    print("warning: SFX not found (run `npx hyperframes skills update`, or set PAPER_COLLAGE_SFX); building without SFX")
    return False


def sfx_cues(html, s):
    """Typing under strips, pop on documents and stickers, click on marks, whoosh on push."""
    cues = [("whoosh-short", 0.0, 0.55, 0.28)] if s["push"] else []
    for m in re.finditer(r'<(\w+)\s+class="([^"]+)"([^>]*)>', html):
        cls, t = m.group(2), re.search(r'data-t="([\d.]+)"', m.group(3))
        if not t:
            continue
        t = float(t.group(1))
        if "cg-strip" in cls:
            cues.append(("typing", t + 0.08, 0.45, 0.2 if "cg-tag" in cls else 0.26))
        elif "cg-person" in cls or "cg-doc" in cls:
            cues.append(("pop", t + (0.25 if "cg-doc" in cls else 0.0), 0.6, 0.34))
        elif "cg-prop" in cls:
            cues.append(("pop", t, 0.6, 0.26))
        elif any(k in cls for k in ("cg-pop", "cg-draw", "cg-doodle")):
            cues.append(("click-soft", t, 0.35, 0.3))
    return [(n, s["start"] + t, d, v) for n, t, d, v in cues if t < s["dur"]]


def audio_tags(cues, real):
    tags, lanes = [], []
    for i, (name, t, d, v) in enumerate(sorted(cues, key=lambda c: c[1])):
        t = real(t)
        lane = next((k for k, busy in enumerate(lanes) if busy <= t), None)
        if lane is None:
            lanes, lane = lanes + [0], len(lanes)
        lanes[lane] = t + d
        tags.append(f'      <audio id="sfx-{i:03d}" src="assets/sfx/{name}.mp3" data-start="{t}" data-duration="{d}" '
                    f'data-track-index="{20 + lane}" data-volume="{v}"></audio>')
    return tags


def write_index(wins, end_real, real, captions, vo, sfx):
    css = (ROOT / "assets/lib/collage.css").read_text() + "\n" + (ROOT / "assets/lib/docs.css").read_text()
    hosts = [f'      <div id="el-{s["id"]}" class="scene" style="z-index: {z}" data-composition-id="{s["id"]}" '
             f'data-composition-src="compositions/{s["id"]}.html" data-start="{real(s["start"])}" data-duration="{real(s["dur"])}" '
             f'data-track-index="{1 + (z - 1) % 2}"></div>' for z, s in enumerate(wins, start=1)]
    if captions:
        hosts.append(f'      <div id="el-captions" class="scene" style="z-index: 50" data-track-kind="captions" data-composition-id="captions" '
                     f'data-composition-src="compositions/captions.html" data-start="0" data-duration="{end_real}" data-track-index="5"></div>')
    if vo:
        hosts.append(f'      <audio id="vo" src="{vo}" data-start="0" data-duration="{end_real}" data-track-index="10" data-volume="1"></audio>')
    hosts += sfx
    script = '\n    <script src="assets/lib/captions.js"></script>' if captions else ""
    html = INDEX_HTML.format(css=css, script=script, end=end_real, body="\n".join(hosts))
    (ROOT / "index.html").write_text(html)


def main():
    wins, end = timeline()
    target = CONFIG.get("target_seconds")
    speed = round(end / target, 6) if target else 1

    def real(t):
        return round(t / speed, 3)

    end_real = real(end)
    htmls = [write_scene(s, speed, real) for s in wins]
    prune_compositions({s["id"] for s in wins} | {"captions"})
    captions = write_captions(end_real, real)
    vo = stretch_vo(speed)
    cues = [c for s, h in zip(wins, htmls) for c in sfx_cues(h, s)] if CONFIG.get("sfx", True) and copy_sfx() else []
    write_index(wins, end_real, real, captions, vo, audio_tags(cues, real))
    print(f"{len(wins)} scenes, {end} s authored, {end_real} s rendered (speed {speed}), {len(cues)} sfx cues")


